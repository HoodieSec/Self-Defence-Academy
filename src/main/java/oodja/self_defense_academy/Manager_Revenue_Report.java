    private void btnTotalRegistrationActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTotalRegistrationActionPerformed
        // TODO add your handling code here:
        String year = cmbYear.getSelectedItem().toString();
        int month = cmbMonth.getSelectedIndex();
        String filter;
        
        if(month == 0){
            filter = year;
        }
        else{
            String buffer = String.format("%02d", month); //Turns into string, add a 0 infront if digit is only singular
            filter = year + "-" + buffer;
        }
        try{
            lblClassRegistration.setText("Total Class Registration: " + PaymentDAO.totalRegistration(filter));
        }
        catch(IOException e){
            JOptionPane.showMessageDialog(this, "Error loading payment records: " + e.getMessage());
        }
    }//GEN-LAST:event_btnTotalRegistrationActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
        model.setRowCount(0);
        String year = cmbYear.getSelectedItem().toString();
        int month = cmbMonth.getSelectedIndex();
        String filter;
        
        if(month == 0){
            filter = year;
        }
        else{
            String buffer = String.format("%02d", month); //Turns into string, add a 0 infront if digit is only singular
            filter = year + "-" + buffer;
        }
        
        try{
            List<String[]> rows = PaymentDAO.getAll();
            for (String[] row : rows){
               if(row[3].startsWith(filter)){
                    model.addRow(row);
               }
            }
        }
        catch(IOException e){
            JOptionPane.showMessageDialog(this, "Error loading payment records: " + e.getMessage());
        }
        if (month == 1 && year.equals("2025")){
            JOptionPane.showMessageDialog(this, "THE CODE WORKSSSS, Sir pls give good grade :) ");
        }
    }//GEN-LAST:event_btnSearchActionPerformed

