    private void loadTable(){
        model.setRowCount(0);
        try{
            List<String[]> rows = PaymentDAO.getAll();
            for (String[] row : rows){
                model.addRow(row);
            }
        }
        catch (IOException e){
            JOptionPane.showMessageDialog(this, "Error loading payment records: " + e.getMessage());
        }
        tblContent.setModel(model); //Set the table collumns and so the table isnt editable 
    }

