    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
        // TODO add your handling code here:
        String name = txtChangeName.getText();
        String email = txtChangeEmail.getText();
        String add = txtChangeAdd.getText();
        String num = txtChangeNum.getText();
        String role = "Administrator";
        String pass = txtPassword.getText();
        if(checkData(email, num) == false){
            return;
        }
         String formatted =  name + "|" + email + "|" + add + "|" + num + "|" + role + "|" + pass ;
         try{
            EmployeeDAO.addNewEntry(formatted);
            this.dispose();
         }
         catch (IOException e){
             JOptionPane.showMessageDialog(this, "Error adding Admin records: " + e.getMessage());
         }
         
    }//GEN-LAST:event_btnSubmitActionPerformed

