    private void loadTable(){
        model.setRowCount(0);
        try{
            List<String[]> rows = EmployeeDAO.getExcludeManager();
            for (String[] row : rows){
                model.addRow(row);
            }
        }
        catch (IOException e){
            JOptionPane.showMessageDialog(this, "Error loading Employee records: " + e.getMessage());
        }
        tblContent.setModel(model); //Set the table collumns and so the table isnt editable 
    }
