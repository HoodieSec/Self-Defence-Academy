    private void btnSearchREALActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchREALActionPerformed
        // TODO add your handling code here:
        model.setRowCount(0);
        String role = cmbRole.getSelectedItem().toString();
        String name = txtName.getText().toString().trim();
       
        try{
            List<String[]> rows = EmployeeDAO.getByRoleORName(role, name);
            for (String[] row : rows){
                    model.addRow(row);
            }
        }
        catch(IOException e){
            JOptionPane.showMessageDialog(this, "Error loading records: " + e.getMessage());
        }
    }//GEN-LAST:event_btnSearchREALActionPerformed

