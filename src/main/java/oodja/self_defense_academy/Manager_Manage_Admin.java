    private void loadTable(){
        model.setRowCount(0);
        try{
            List<String[]> rows = EmployeeDAO.getAdminOnly();
            for (String[] row : rows){
                model.addRow(row);
            }
        }
        catch (IOException e){
            JOptionPane.showMessageDialog(this, "Error loading Admin records: " + e.getMessage());
        }
        tblContent.setModel(model); //Set the table collumns and so the table isnt editable 
    }
    
