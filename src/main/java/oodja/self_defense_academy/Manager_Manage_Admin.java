    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
        model.setRowCount(0);
        int type = cmbSearchBy.getSelectedIndex();
        String filter = txtFilter.getText().toString().trim();

        try{
           if(type == 0){
            String[] row = EmployeeDAO.getByAdminId(txtFilter.getText());
                model.addRow(row);
           }
           else if(type == 1){
            List<String[]> rows = EmployeeDAO.getByAdminName(txtFilter.getText());
                for (String[] row : rows){
                    model.addRow(row);
                }
           }
           else if(type == 2){
            List<String[]> rows = EmployeeDAO.getByAdminEmail(txtFilter.getText());
                for (String[] row : rows){
                    model.addRow(row);
                }
           }
           else if(type == 3){
            List<String[]> rows = EmployeeDAO.getByAdminAddress(txtFilter.getText());
                for (String[] row : rows){
                    model.addRow(row);
                }
           }
           else if(type == 4){
            List<String[]> rows = EmployeeDAO.getByAdminPhone(txtFilter.getText());
                for (String[] row : rows){
                    model.addRow(row);
                }
           }
            
        }
        catch(IOException e){
            JOptionPane.showMessageDialog(this, "Error loading records: " + e.getMessage());
        }
    }//GEN-LAST:event_btnSearchActionPerformed
    
    
   
    
 
    
