    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        // TODO add your handling code here:
        if(checkSelectedItem() == false){
            return;
        }
        
        String id = lblId.getText();
        String name = txtChangeName.getText();
        String email = txtChangeEmail.getText();
        String add = txtChangeAdd.getText();
        String num = txtChangeNum.getText();
        if(checkData(email, num) == false){
            return;
        }
        try{
            String[] row = EmployeeDAO.getById(id);
            String formatted = id + "|" + name + "|" + email + "|" + add + "|" + num + "|" + row[5] + "|" + row[6];
            EmployeeDAO.updateById(id, formatted);
        }
        catch (IOException e){
            JOptionPane.showMessageDialog(this, "Error loading records: " + e.getMessage());
        }
        
        
        
    }//GEN-LAST:event_btnEditActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        checkSelectedItem();
        String id = lblId.getText();
        // Confirmation before delete
        int choice = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete record " + id + "?","Confirm Delete", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        
        if (choice != JOptionPane.YES_OPTION) {
        return;
    }
     try {
        EmployeeDAO.deleteById(id); 
    } 
     catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error deleting record: " + e.getMessage());
    }
        
    }//GEN-LAST:event_btnDeleteActionPerformed

