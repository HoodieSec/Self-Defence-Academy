    private boolean checkData(String email, String phone){
        
        if(!email.contains("@")){
            JOptionPane.showMessageDialog(null, "Please enter a valid email", "Error", JOptionPane.ERROR_MESSAGE);
            return false;
        }
        try{
            Integer.parseInt(phone.trim());
        }
        catch(NumberFormatException e){
            JOptionPane.showMessageDialog(null, "Please enter a phone number", "Error", JOptionPane.ERROR_MESSAGE);
            return false;
        }
        return true;
    }
    
    private boolean checkSelectedItem(){
        if(tblContent.getSelectedRow() == -1){
            JOptionPane.showMessageDialog(null, "Please select a row", "Error", JOptionPane.ERROR_MESSAGE);
            return false;
        }
        return true;
    }
    
    

